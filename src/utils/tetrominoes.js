// 随机生成一个方块类型
export function randomTetrominoType() {
  const types = Object.keys(TETROMINOES);
  return types[Math.floor(Math.random() * types.length)];
}

// 创建一个新方块
export function createTetromino(type) {
  const data = TETROMINOES[type];
  return {
    type,
    color: data.color,
    glow: data.glow,
    rotation: 0,
    shape: data.shapes[0],
    x: Math.floor((10 - data.shapes[0][0].length) / 2),
    y: 0,
  };
}
